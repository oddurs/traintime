import { readFileSync } from "node:fs";
import { join } from "node:path";
import type { Metadata } from "next";
import { BASE_PATH } from "@/lib/basePath";

export const metadata: Metadata = {
  title: "How accurate is bound?",
  description: "Measured error of bound's simulated NYC subway positions, against the arrivals the MTA's own feed reported.",
};

interface Accuracy {
  generatedAt: string;
  report: string;
  usesModel: boolean;
  window: { from: number; to: number };
  ticks: number;
  arrivals: number;
  dataLatencyS: { median: number; p90: number };
  eta: { bucket: string; label: string; n: number; mtaMae: number; mtaBias: number; ourMae: number; ourBias: number; coverage: number }[];
  position: { n: number; behindSegment: number; shortMedianM: number; shortP90M: number; earlyShare: number; earlyMedianS: number };
  motion: { steps: number; reversals: number; jumps: number; coldPlacements: number; maxSpeedMps: number; maxAccelMps2: number };
  baseline: { name: string; shortMedianM: number; reversals: number; steps: number } | null;
  learned: { window: { from: string; to: string }; events: number; etaObs: number; segments: number; stops: number } | null;
  model: { generatedAt: string; mae_raw: number; mae_tables: number; mae_model: number; n_train: number; n_test: number } | null;
}

function load(): Accuracy | null {
  try {
    return JSON.parse(readFileSync(join(process.cwd(), "public", "data", "accuracy.json"), "utf8")) as Accuracy;
  } catch {
    return null;
  }
}

const n0 = (x: number) => Math.round(x).toLocaleString();
const s1 = (x: number) => `${x.toFixed(1)} s`;
const pct = (x: number) => `${Math.round(x * 100)}%`;
const day = (ts: number) => new Date(ts * 1000).toLocaleString("en-US", { timeZone: "America/New_York", dateStyle: "medium", timeStyle: "short" });

export default function AccuracyPage() {
  const a = load();

  return (
    <div className="doc">
      <a className="back" href={`${BASE_PATH}/`}>← back to the map</a>
      <header>
        <h1>How accurate is bound?</h1>
        <p>
          The MTA does not publish where its trains are. bound works out each position from predicted
          arrival times and a coarse vehicle status, so the honest question is: how wrong is it? These
          numbers come from replaying recorded feed data through the very same code the map runs, and
          scoring it against the arrival timestamps the MTA later reported. Nothing here is hand-picked —
          it is regenerated by <code>npm run evaluate &amp;&amp; npm run publish-accuracy</code>.
        </p>
      </header>

      {!a && (
        <p className="stale">
          No evaluation has been published yet. Run the poller for a while, then <code>npm run evaluate</code>.
        </p>
      )}

      {a && (
        <>
          <h2>Predicting the next arrival</h2>
          <p>
            Every few seconds the feed re-states when each train will reach its next stop. We correct that
            prediction using what the same stretch of track has actually done before. Both are scored against
            the moment the train really arrived, over {n0(a.arrivals)} arrivals.
          </p>
          <table>
            <thead>
              <tr>
                <th>time until arrival</th>
                <th className="num">samples</th>
                <th className="num">MTA error</th>
                <th className="num">bound error</th>
                <th className="num">within our ±1σ</th>
              </tr>
            </thead>
            <tbody>
              {a.eta.map((e) => (
                <tr key={e.bucket}>
                  <td>{e.label}</td>
                  <td className="num">{n0(e.n)}</td>
                  <td className="num">{s1(e.mtaMae)}</td>
                  <td className="num"><span className={e.ourMae < e.mtaMae ? "win" : undefined}>{s1(e.ourMae)}</span></td>
                  <td className="num">{pct(e.coverage)}</td>
                </tr>
              ))}
            </tbody>
          </table>
          <p>
            Error is the mean absolute difference from the real arrival. The last column is calibration: when
            bound says &ldquo;3 minutes, give or take 20 seconds&rdquo;, how often the truth lands inside that
            range. A perfectly calibrated 1σ would sit at 68%.
          </p>

          <h2>Where the marker actually was</h2>
          <p>
            At the instant each train really arrived, how far from the platform was its dot?
          </p>
          <table>
            <tbody>
              <tr><td>median distance short of the platform</td><td className="num">{n0(a.position.shortMedianM)} m</td></tr>
              <tr><td>90th percentile</td><td className="num">{n0(a.position.shortP90M)} m</td></tr>
              <tr><td>already drawn at the platform early</td><td className="num">{pct(a.position.earlyShare)}{a.position.earlyShare > 0 ? `, by ${n0(a.position.earlyMedianS)} s` : ""}</td></tr>
              {a.baseline && (
                <tr><td>a naive straight interpolation, for comparison</td><td className="num">{n0(a.baseline.shortMedianM)} m</td></tr>
              )}
            </tbody>
          </table>
          <p>
            A few hundred metres is what a ~30 second timing error looks like at subway speeds. This number
            follows the table above: better arrival estimates put the dot in a better place.
          </p>

          <h2>Does it move like a train?</h2>
          <p>
            Position is integrated with acceleration and braking limits and a controller that paces the train
            to its predicted arrival, so corrections change where it is heading rather than teleporting it.
            Over {n0(a.motion.steps)} simulated train-seconds:
          </p>
          <table>
            <tbody>
              <tr><td>times a train moved backwards</td><td className="num">{n0(a.motion.reversals)}</td></tr>
              <tr><td>jumps faster than 40 m/s</td><td className="num">{n0(a.motion.jumps)}</td></tr>
              <tr><td>fastest speed drawn</td><td className="num">{(a.motion.maxSpeedMps * 3.6).toFixed(0)} km/h</td></tr>
              <tr><td>hardest acceleration drawn</td><td className="num">{a.motion.maxAccelMps2.toFixed(1)} m/s²</td></tr>
            </tbody>
          </table>

          <h2>What it learned from</h2>
          <p>
            {a.learned
              ? `Timing tables built from ${n0(a.learned.events)} recorded station events and ${n0(a.learned.etaObs)} prediction revisions, covering ${n0(a.learned.segments)} stretches of track and ${n0(a.learned.stops)} platforms.`
              : "Schedule and geometry only — no recordings had been made when this was published."}
            {a.model && ` A gradient-boosted correction sits on top, trained on ${n0(a.model.n_train)} observations and held out against ${n0(a.model.n_test)} later ones, where it scored ${s1(a.model.mae_model)} against the MTA's ${s1(a.model.mae_raw)}.`}
          </p>

          <h3>Caveats worth knowing</h3>
          <ul>
            <li>Departures are only reported on the numbered lines and the L. On the lettered lines bound models them, so those trains leave a platform on an estimate.</li>
            <li>A train first seen mid-run has no history, so its previous stop is inferred; the map says so when you open it.</li>
            <li>Data reaches us a median of {s1(a.dataLatencyS.median)} after the event it describes, so even a perfect model is that far behind reality.</li>
            <li>These figures come from one window ({day(a.window.from)} to {day(a.window.to)}) and will shift with more recording.</li>
          </ul>

          <p className="muted">
            Published {new Date(a.generatedAt).toLocaleString("en-US", { dateStyle: "medium", timeStyle: "short" })} from the <code>{a.report}</code> run.
            Method and code: <a href="https://github.com/oddurs/traintime">github.com/oddurs/traintime</a>.
          </p>
        </>
      )}
    </div>
  );
}
